create table if not exists public.site_users (
  id uuid primary key default gen_random_uuid(),
  username text not null unique,
  password_hash text not null,
  display_name text not null default '',
  phone text not null default '',
  email text not null default '',
  marketing_emails_opt_in boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.site_users add column if not exists marketing_emails_opt_in boolean not null default false;

alter table public.dresses add column if not exists submitter_user_id uuid references public.site_users(id) on delete set null;

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  dress_id uuid not null references public.dresses(id) on delete cascade,
  customer_name text not null,
  customer_phone text not null,
  customer_email text not null,
  event_date date not null,
  status text not null default 'confirmed',
  amount_total numeric,
  platform_fee numeric,
  owner_payout numeric,
  tranzila_index text,
  payment_confirmed_at timestamptz,
  site_user_id uuid,
  payment_method text,
  payment_reported_at timestamptz,
  owner_response_deadline timestamptz,
  owner_reminder_sent_at timestamptz,
  owner_responded_at timestamptz,
  owner_reject_reason text,
  payment_sender_name text,
  payment_sender_phone text,
  payment_deadline timestamptz,
  created_at timestamptz not null default now()
);

alter table public.bookings drop constraint if exists bookings_status_check;
alter table public.bookings add constraint bookings_status_check
  check (status in (
    'pending_owner_approval',
    'pending_payment',
    'awaiting_admin_approval',
    'confirmed',
    'cancelled',
    'failed'
  ));

create table if not exists public.dress_ratings (
  id bigint generated by default as identity primary key,
  dress_id uuid not null references public.dresses(id) on delete cascade,
  customer_name text not null,
  stars integer not null check (stars between 1 and 5),
  review_text text not null default '',
  status text not null default 'pending',
  rater_user_id uuid references public.site_users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null,
  role text not null default 'לקוחה',
  review_text text not null,
  stars integer not null default 5 check (stars >= 1 and stars <= 5),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);
